const mongoose = require('mongoose');

const aiTaskLogSchema = new mongoose.Schema({
  taskId: {
    type: String,
    required: true,
    index: true
  },
  taskName: {
    type: String,
    required: true
  },
  adminUser: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User'
  },
  adminName: {
    type: String,
    default: 'Administrator'
  },
  params: {
    type: mongoose.Schema.Types.Mixed,
    default: {}
  },
  status: {
    type: String,
    enum: ['success', 'failed'],
    default: 'success'
  },
  executionTimeMs: {
    type: Number,
    default: 0
  },
  // Ground truth numerical metrics computed 100% by backend
  metrics: {
    type: mongoose.Schema.Types.Mixed,
    default: {}
  },
  // Structured insights generated by Gemini AI
  analysis: {
    summary: { type: String, default: '' },
    keyObservations: [{ type: String }],
    warnings: [{ type: String }],
    dataGaps: [{ type: String }],
    recommendations: [{ type: String }]
  },
  errorMessage: {
    type: String,
    default: null
  }
}, {
  timestamps: true
});

module.exports = mongoose.models.AITaskLog || mongoose.model('AITaskLog', aiTaskLogSchema);

